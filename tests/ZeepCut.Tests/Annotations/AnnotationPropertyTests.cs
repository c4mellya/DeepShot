using Xunit;
using ZeepCut.Core.Annotations;
using ZeepCut.Core.Geometry;

namespace ZeepCut.Tests.Annotations;

public class AnnotationPropertyTests
{
    [Fact]
    public void Defaults_AreAppliedToEveryAnnotation()
    {
        var rectangle = new RectangleAnnotation(new PixelRect(0, 0, 10, 10));
        var ellipse = new EllipseAnnotation(new PixelRect(0, 0, 10, 10));
        var arrow = new ArrowAnnotation(new PixelPoint(0, 0), new PixelPoint(10, 10));
        var line = new LineAnnotation(new PixelPoint(0, 0), new PixelPoint(10, 10));
        var freehand = new FreehandAnnotation(new[] { new PixelPoint(0, 0) });
        var text = new TextAnnotation(new PixelPoint(0, 0), "文字");
        var mosaic = new MosaicAnnotation(new PixelRect(0, 0, 10, 10));

        foreach (var annotation in new Annotation[] { rectangle, ellipse, arrow, line, freehand, text, mosaic })
        {
            Assert.Equal(AnnotationColor.Default, annotation.Color);
            Assert.Equal(AnnotationDefaults.DefaultThickness, annotation.Thickness);
            Assert.NotEqual(Guid.Empty, annotation.Id);
            Assert.Equal(0, annotation.CreationOrder);
        }

        Assert.Equal(AnnotationDefaults.DefaultFontSize, text.FontSize);
        Assert.Null(text.BackgroundColor);
        Assert.Equal(AnnotationDefaults.DefaultMosaicBlockSize, mosaic.BlockSize);
        Assert.Equal(AnnotationDefaults.DefaultMosaicStrength, mosaic.Strength, precision: 10);
        Assert.False(freehand.Smooth);
    }

    [Fact]
    public void Id_AutoGenerated_IsUnique()
    {
        var first = new RectangleAnnotation(new PixelRect(0, 0, 10, 10));
        var second = new RectangleAnnotation(new PixelRect(0, 0, 10, 10));

        Assert.NotEqual(first.Id, second.Id);
    }

    [Fact]
    public void Id_ExplicitValue_IsPreserved()
    {
        var id = Guid.NewGuid();

        var annotation = new RectangleAnnotation(new PixelRect(0, 0, 10, 10), id: id);

        Assert.Equal(id, annotation.Id);
    }

    [Fact]
    public void Id_EmptyGuid_Throws()
    {
        Assert.Throws<ArgumentException>(() =>
            new RectangleAnnotation(new PixelRect(0, 0, 10, 10), id: Guid.Empty));
    }

    [Theory]
    [InlineData(-100, AnnotationDefaults.MinThickness)]
    [InlineData(0, AnnotationDefaults.MinThickness)]
    [InlineData(1, 1)]
    [InlineData(5, 5)]
    [InlineData(20, 20)]
    [InlineData(21, AnnotationDefaults.MaxThickness)]
    [InlineData(999, AnnotationDefaults.MaxThickness)]
    public void Thickness_IsClampedInConstructor(int input, int expected)
    {
        var annotation = new RectangleAnnotation(new PixelRect(0, 0, 10, 10), thickness: input);

        Assert.Equal(expected, annotation.Thickness);
    }

    [Theory]
    [InlineData(-100, AnnotationDefaults.MinThickness)]
    [InlineData(21, AnnotationDefaults.MaxThickness)]
    [InlineData(7, 7)]
    public void Thickness_IsClampedOnAssignment(int input, int expected)
    {
        var annotation = new RectangleAnnotation(new PixelRect(0, 0, 10, 10));

        annotation.Thickness = input;

        Assert.Equal(expected, annotation.Thickness);
    }

    [Theory]
    [InlineData(-5, AnnotationDefaults.MinFontSize)]
    [InlineData(7, AnnotationDefaults.MinFontSize)]
    [InlineData(8, 8)]
    [InlineData(72, 72)]
    [InlineData(73, AnnotationDefaults.MaxFontSize)]
    [InlineData(1000, AnnotationDefaults.MaxFontSize)]
    public void FontSize_IsClamped(int input, int expected)
    {
        var annotation = new TextAnnotation(new PixelPoint(0, 0), "A", fontSize: input);

        Assert.Equal(expected, annotation.FontSize);
    }

    [Fact]
    public void FontSize_AssignmentClampsAndUpdatesLineHeight()
    {
        var annotation = new TextAnnotation(new PixelPoint(0, 0), "A", fontSize: 20);

        annotation.FontSize = 1000;
        Assert.Equal(AnnotationDefaults.MaxFontSize, annotation.FontSize);
        Assert.Equal((int)Math.Ceiling(AnnotationDefaults.MaxFontSize * TextAnnotation.LineHeightFactor),
            annotation.LineHeight);

        annotation.FontSize = 0;
        Assert.Equal(AnnotationDefaults.MinFontSize, annotation.FontSize);
    }

    [Theory]
    [InlineData(-1, AnnotationDefaults.MinMosaicBlockSize)]
    [InlineData(3, AnnotationDefaults.MinMosaicBlockSize)]
    [InlineData(4, 4)]
    [InlineData(64, 64)]
    [InlineData(65, AnnotationDefaults.MaxMosaicBlockSize)]
    [InlineData(1000, AnnotationDefaults.MaxMosaicBlockSize)]
    public void MosaicBlockSize_IsClamped(int input, int expected)
    {
        var annotation = new MosaicAnnotation(new PixelRect(0, 0, 10, 10), blockSize: input);

        Assert.Equal(expected, annotation.BlockSize);
    }

    [Theory]
    [InlineData(-1d, AnnotationDefaults.MinMosaicStrength)]
    [InlineData(0d, AnnotationDefaults.MinMosaicStrength)]
    [InlineData(0.5d, 0.5d)]
    [InlineData(1d, AnnotationDefaults.MaxMosaicStrength)]
    [InlineData(2d, AnnotationDefaults.MaxMosaicStrength)]
    [InlineData(double.NaN, AnnotationDefaults.DefaultMosaicStrength)]
    public void MosaicStrength_IsClamped(double input, double expected)
    {
        var annotation = new MosaicAnnotation(new PixelRect(0, 0, 10, 10), strength: input);

        Assert.Equal(expected, annotation.Strength, precision: 10);
    }

    [Fact]
    public void MosaicStrength_AssignmentClamps()
    {
        var annotation = new MosaicAnnotation(new PixelRect(0, 0, 10, 10));

        annotation.Strength = 5d;
        Assert.Equal(1d, annotation.Strength, precision: 10);

        annotation.Strength = -5d;
        Assert.Equal(0d, annotation.Strength, precision: 10);

        annotation.Strength = double.NaN;
        Assert.Equal(AnnotationDefaults.DefaultMosaicStrength, annotation.Strength, precision: 10);
    }

    [Fact]
    public void AnnotationColor_ChannelsRoundTrip()
    {
        var color = AnnotationColor.FromArgb(128, 10, 20, 30);

        Assert.Equal((byte)128, color.Alpha);
        Assert.Equal((byte)10, color.Red);
        Assert.Equal((byte)20, color.Green);
        Assert.Equal((byte)30, color.Blue);
        Assert.Equal(0x800A141Eu, color.Argb);
    }

    [Fact]
    public void AnnotationColor_FromRgb_IsOpaque()
    {
        var color = AnnotationColor.FromRgb(1, 2, 3);

        Assert.Equal(byte.MaxValue, color.Alpha);
        Assert.Equal(0xFF010203u, color.Argb);
    }

    [Fact]
    public void AnnotationColor_EqualityIsByArgb()
    {
        Assert.Equal(new AnnotationColor(0xFF112233), AnnotationColor.FromArgb(0xFF, 0x11, 0x22, 0x33));
        Assert.NotEqual(new AnnotationColor(0xFF112233), new AnnotationColor(0xFF112234));
    }

    [Fact]
    public void AnnotationColor_CanBeAssignedToAnnotation()
    {
        var annotation = new RectangleAnnotation(new PixelRect(0, 0, 10, 10));
        var color = AnnotationColor.FromRgb(0, 200, 100);

        annotation.Color = color;

        Assert.Equal(color, annotation.Color);
    }

    [Fact]
    public void Text_NullText_BecomesEmpty()
    {
        var annotation = new TextAnnotation(new PixelPoint(0, 0), null!);

        Assert.Equal(string.Empty, annotation.Text);
    }

    [Fact]
    public void Text_TextAssignment_UpdatesBounds()
    {
        var annotation = new TextAnnotation(new PixelPoint(0, 0), "A", fontSize: 20);
        var widthBefore = annotation.Bounds.Width;

        annotation.Text = "AAAA";

        Assert.True(annotation.Bounds.Width > widthBefore);
    }

    [Fact]
    public void Text_BackgroundColor_IsOptional()
    {
        var annotation = new TextAnnotation(new PixelPoint(0, 0), "A");

        annotation.BackgroundColor = AnnotationColor.White;
        Assert.Equal(AnnotationColor.White, annotation.BackgroundColor);

        annotation.BackgroundColor = null;
        Assert.Null(annotation.BackgroundColor);
    }

    [Fact]
    public void Freehand_SmoothFlag_IsMutable()
    {
        var annotation = new FreehandAnnotation(new[] { new PixelPoint(0, 0) });

        annotation.Smooth = true;

        Assert.True(annotation.Smooth);
    }
}
